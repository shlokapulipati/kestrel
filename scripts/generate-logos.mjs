// Copies the SVG path of each known tool's logo from the simple-icons package
// into src/catalog/logos.generated.ts, so the app bundles them locally and
// never loads an image from the network. Run: npm run logos:generate
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")

// Kestrel tool id -> simple-icons slug. Java is intentionally not mapped yet.
const SLUGS = {
  node: "nodedotjs",
  git: "git",
  redis: "redis",
  kafka: "apachekafka",
  mongodb: "mongodb",
}

const logos = {}
for (const [toolId, slug] of Object.entries(SLUGS)) {
  const file = path.join(root, "node_modules", "simple-icons", "icons", `${slug}.svg`)
  if (!existsSync(file)) {
    console.warn(`skip ${toolId}: icon file ${slug}.svg not found`)
    continue
  }
  const svg = readFileSync(file, "utf8")
  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1] ?? toolId
  const pathData = /<path[^>]*\sd="([^"]+)"/.exec(svg)?.[1]
  if (!pathData) {
    console.warn(`skip ${toolId}: no path found in ${slug}.svg`)
    continue
  }
  logos[toolId] = { title, path: pathData }
}

if (Object.keys(logos).length === 0) {
  console.error("No logos were found. Nothing written.")
  process.exit(1)
}

const header =
  "// GENERATED by scripts/generate-logos.mjs from the simple-icons package.\n" +
  "// Do not edit by hand. Regenerate with: npm run logos:generate\n" +
  "// Logos are trademarks of their owners, used only to identify each tool.\n\n"
const body =
  "export type Logo = { title: string; path: string }\n\n" +
  `export const LOGOS: Record<string, Logo> = ${JSON.stringify(logos, null, 2)}\n`

writeFileSync(path.join(root, "src", "catalog", "logos.generated.ts"), header + body)
console.log(`Wrote ${Object.keys(logos).length} logos: ${Object.keys(logos).join(", ")}`)